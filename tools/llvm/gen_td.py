"""Generate the LLVM PI32V2 target's instruction descriptions from the instruction table.

    python3 tools/llvm/gen_td.py LLVM_TARGET_DIR [--table isa/pi32v2.toml]

Writes, into LLVM_TARGET_DIR (llvm/lib/Target/PI32V2 of the LLVM tree):

  PI32V2InstrGen.td        operand definitions and one instruction per table form and enum combination
  PI32V2OperandsGen.inc    the C++ the operands name: decoders, encoders and printers (sections selected with
                           PI32V2_GEN_DECODERS, PI32V2_GEN_ENCODER_DECLS, PI32V2_GEN_ENCODERS,
                           PI32V2_GEN_PRINTER_DECLS, PI32V2_GEN_PRINTERS)
  PI32V2InstrIds.txt       LLVM instruction name -> table id and enum values (for tests and tools)
  AsmParser/PI32V2ParserGen.inc   the assembler's templates (tools/llvm/gen_parser.py)
  MCTargetDesc/PI32V2CompressGen.inc the shorter form JieLi's assembler would use for a code generator form
                           (tools/llvm/gen_compress.py)
  MCTargetDesc/PI32V2RelaxGen.inc    branch relaxation: each branch form's next larger form (tools/llvm/gen_parser.py)
  MCTargetDesc/PI32V2FixupsGen.inc   the fixup kinds: where a branch target or a 32-bit constant is in each
                           instruction that can take a symbol, and its ELF relocation (docs/ELF.md section 5)

and, with --tests DIR (llvm/test/MC of the LLVM tree), Disassembler/PI32V2/examples.txt: every example of the
table as a llvm-mc --disassemble test that must print the table's text.

How the table maps to TableGen (docs/LLVM.md):
- Each `enum` field is expanded: one instruction per combination of enum values, the value's text written into
  the assembly string and its bits fixed in the encoding. 1165 forms become about 4200 instructions.
- The encoding is `Inst`, 16, 32 or 48 bits, the first word in the high bits (the word order of the table);
  the code emitter writes the words in order, each little-endian. A `-` bit is left unset (`?`).
- Registers: gpr -> GPR, gpr_lo -> GPRLo, gpr_hi -> GPRHi (encoded as the register number - 8), pair -> GPRPair,
  sr -> SR. Every other field is an immediate operand holding the value the syntax shows (a uimm/simm is
  already scaled, a bit operand is the bit's value, a modified immediate its 32-bit value); register lists
  and masks hold the raw field.
- A form whose syntax starts `{x} =` writes x (an output operand); `{x} op= ...` reads and writes it (output
  tied to an input). Everything else is an input. This is what the assembly says, not a full semantics.
- A branch or call target (`goto {n}`, `call {n}`, `gotoss {n}`) is a pc-relative operand, its value the
  displacement from the end of the instruction as printed.
- Forms with no assembler syntax (`asm_no_syntax`) are in the assembly variant "disasm", so the matcher of the
  default variant never chooses them.
"""
import argparse
import re
import sys
from itertools import product
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT))
from pi32v2isa import codec, table  # noqa: E402
from pi32v2isa.table import SYNTAX_TOKEN  # noqa: E402

REG_CLASS = {"gpr": "GPR", "gpr_lo": "GPRLo", "gpr_hi": "GPRHi", "pair": "GPRPair", "sr": "SR"}
COMPOUND = ("+=", "-=", "*=", "<<=", "<<<=", ">>=", ">>>=", "<>=", "<c>=", "><=", "|=", "^=", "&=", "<=")
FEATURES = {"instrev3": "HasInstRev3", "fprev1": "HasFPRev1"}
HEADER = ("Generated by pi32v2-isa tools/llvm/gen_td.py from isa/pi32v2.toml; do not edit. "
          "Regenerate from the table.")


def branch_field(insn):
    """The field holding a pc-relative target, or None (as pi32v2isa.asm.branch_field)."""
    m = re.search(r"\b(?:goto|call|gotoss) \{(\w)\}(?: \(\w\))?$", insn.syntax)
    if m and insn.fields[m.group(1)].kind == "simm":
        return m.group(1)
    return None


def record_name(insn_id, combo_index, ncombos):
    name = re.sub(r"[^A-Za-z0-9]", "_", insn_id).upper()
    return f"{name}_E{combo_index}" if ncombos > 1 else name


class Operand:
    """One operand type: a TableGen Operand (or a register class) and the C++ that goes with it."""

    def __init__(self, kind, key, td_name, td, decoder=None, encoder=None, printer=None):
        self.kind, self.key, self.td_name, self.td = kind, key, td_name, td
        self.decoder, self.encoder, self.printer = decoder, encoder, printer


class Operands:
    def __init__(self):
        self.by_key = {}

    def get(self, insn, name, plus):
        f = insn.fields[name]
        width = len(insn.field_bits(name))
        if f.kind in REG_CLASS:
            return Operand(f.kind, f.kind, REG_CLASS[f.kind], None)
        target = branch_field(insn) == name
        if target:              # a branch's target is a basic block, a call's a symbol
            key = ("target", width, f.scale, "call" if re.search(r"\bcall\b", insn.syntax) else "goto")
        elif f.kind in ("uimm", "simm"):
            key = (f.kind, width, f.scale, f.add, f.zero_as, plus)
        elif f.kind == "modimm":
            key = ("modimm", f.invert, f.decimal, plus)
        elif f.kind in ("bit", "invbit", "rlist4", "pair_regs"):
            key = (f.kind, plus)
        elif f.kind == "rmask":
            key = ("rmask", f.lead)
        elif f.kind == "srmask":
            key = ("srmask", width)
        else:
            raise SystemExit(f"{insn.id}: no operand type for kind {f.kind}")
        if key not in self.by_key:
            self.by_key[key] = self._make(key)
        return self.by_key[key]

    def _make(self, key):
        kind = key[0]
        def part(x):
            if x is True or x is False or x is None:
                return {True: "T", False: "F", None: "N"}[x]
            return str(x).replace("-", "m") or "E"
        name = "Op" + "_".join(part(x) for x in key)
        name = re.sub(r"[^A-Za-z0-9_]", "_", name)
        dec, enc, prt = f"decode{name}", f"get{name}Value", f"print{name}"
        optype = "OPERAND_PCREL" if kind == "target" else "OPERAND_IMMEDIATE"
        vt = "OtherVT" if kind == "target" and key[3] == "goto" else "i32"
        td = (f"def {name} : Operand<{vt}> {{\n  let DecoderMethod = \"{dec}\";\n  let EncoderMethod = \"{enc}\";\n"
              f"  let PrintMethod = \"{prt}\";\n  let OperandType = \"{optype}\";\n}}\n")
        return Operand(kind, key, name, td, dec, enc, prt)

    def cxx(self, section):
        out = []
        for op in self.by_key.values():
            out.append(getattr(self, "_" + section)(op))
        return "\n".join(x for x in out if x)

    # ---- C++ per operand type
    def _decoders(self, op):
        k = op.key
        head = (f"static DecodeStatus {op.decoder}(MCInst &Inst, uint64_t Raw, uint64_t Address,\n"
                f"    const MCDisassembler *Decoder) {{\n")
        if k[0] == "target":
            _, width, scale, _ = k
            body = (f"  int64_t V = SignExtend64<{width}>(Raw) * {scale};\n"
                    f"  Inst.addOperand(MCOperand::createImm(V));\n")
        elif k[0] in ("uimm", "simm"):
            kind, width, scale, add, zero_as, _ = k
            raw = f"SignExtend64<{width}>(Raw)" if kind == "simm" else "(int64_t)Raw"
            body = ""
            if zero_as is not None:
                body += f"  if (Raw == 0) {{ Inst.addOperand(MCOperand::createImm({zero_as})); return MCDisassembler::Success; }}\n"
            body += (f"  int64_t V = {raw} * ({scale}) + ({add});\n"
                     f"  Inst.addOperand(MCOperand::createImm(V));\n")
        elif k[0] == "modimm":
            _, invert, _, _ = k
            body = (f"  uint32_t V = PI32V2::modImmValue(Raw){' ^ 0xFFFFFFFFu' if invert else ''};\n"
                    f"  Inst.addOperand(MCOperand::createImm(V));\n")
        elif k[0] == "bit":
            body = "  Inst.addOperand(MCOperand::createImm((int64_t)(1u << Raw)));\n"
        elif k[0] == "invbit":
            body = "  Inst.addOperand(MCOperand::createImm((int64_t)(0xFFFFFFFFu ^ (1u << Raw))));\n"
        else:                                       # register lists and masks: the raw field
            body = "  Inst.addOperand(MCOperand::createImm((int64_t)Raw));\n"
        return head + body + "  return MCDisassembler::Success;\n}\n"

    def _encoder_decls(self, op):
        return (f"uint64_t {op.encoder}(const MCInst &MI, unsigned OpNo, SmallVectorImpl<MCFixup> &Fixups,\n"
                f"    const MCSubtargetInfo &STI) const;")

    def _encoders(self, op):
        k = op.key
        head = (f"uint64_t PI32V2MCCodeEmitter::{op.encoder}(const MCInst &MI, unsigned OpNo,\n"
                f"    SmallVectorImpl<MCFixup> &Fixups, const MCSubtargetInfo &STI) const {{\n"
                f"  const MCOperand &MO = MI.getOperand(OpNo);\n")
        if k[0] == "target":
            _, width, scale, _ = k
            body = (f"  if (!MO.isImm())\n    return encodeTargetExpr(MI, OpNo, {width}, Fixups, STI);\n"
                    f"  return (uint64_t)(MO.getImm() / {scale}) & ((1ull << {width}) - 1);\n")
        elif k[0] in ("uimm", "simm"):
            kind, width, scale, add, zero_as, _ = k
            body = "  if (!MO.isImm())\n"
            body += f"    return encodeImmExpr(MI, OpNo, {width}, Fixups, STI);\n"
            body += "  int64_t V = MO.getImm();\n"
            if zero_as is not None:
                body += f"  if (V == {zero_as})\n    return 0;\n"
            body += f"  return (uint64_t)((V - ({add})) / ({scale})) & ((1ull << {width}) - 1);\n"
        elif k[0] == "modimm":
            _, invert, _, _ = k
            body = f"  return PI32V2::modImmRaw((uint32_t)MO.getImm(){' ^ 0xFFFFFFFFu' if invert else ''});\n"
        elif k[0] == "bit":
            body = "  return llvm::countr_zero((uint32_t)MO.getImm());\n"
        elif k[0] == "invbit":
            body = "  return llvm::countr_zero(~(uint32_t)MO.getImm());\n"
        else:
            body = "  return (uint64_t)MO.getImm();\n"
        return head + body + "}\n"

    def _printer_decls(self, op):
        if op.key[0] == "target":           # pc-relative: the printer is also given the address
            return f"void {op.printer}(const MCInst *MI, uint64_t Address, unsigned OpNo, raw_ostream &O);"
        return f"void {op.printer}(const MCInst *MI, unsigned OpNo, raw_ostream &O);"

    def _printers(self, op):
        k = op.key
        address = "uint64_t Address, " if k[0] == "target" else ""
        head = (f"void PI32V2InstPrinter::{op.printer}(const MCInst *MI, {address}unsigned OpNo, raw_ostream &O) {{\n"
                f"  const MCOperand &MO = MI->getOperand(OpNo);\n"
                f"  if (!MO.isImm()) {{\n    MAI.printExpr(O, *MO.getExpr());\n    return;\n  }}\n")
        plus = k[-1] is True and k[0] in ("uimm", "simm", "modimm", "bit", "invbit", "rlist4", "pair_regs")
        if k[0] in ("target", "uimm", "simm"):
            text = "std::to_string(MO.getImm())"
        elif k[0] == "modimm":
            _, _, decimal, _ = k
            text = ("std::to_string((uint32_t)MO.getImm())" if decimal else
                    "PI32V2::hexUpper((uint32_t)MO.getImm())")
        elif k[0] in ("bit", "invbit"):
            text = "std::to_string((uint32_t)MO.getImm())"
        elif k[0] == "rlist4":
            text = "PI32V2::rlist4Text(MO.getImm())"
        elif k[0] == "pair_regs":
            text = "PI32V2::pairRegsText(MO.getImm())"
        elif k[0] == "rmask":
            text = f"PI32V2::rmaskText(MO.getImm(), \"{k[1]}\")"
        elif k[0] == "srmask":
            text = f"PI32V2::srmaskText(MO.getImm(), {k[1]})"
        if plus:
            body = f"  std::string T = {text};\n  if (T != \"0\")\n    O << '+' << T;\n"
        else:
            body = f"  O << {text};\n"
        return head + body + "}\n"


def asm_string(syntax, combo_text, plus_names):
    """The TableGen AsmString of a syntax: fields as ${x}, enum fields replaced by their text, escaped."""
    out = []
    pos = 0
    for m in SYNTAX_TOKEN.finditer(syntax):
        out.append(escape(syntax[pos:m.start()]))
        tok = m.group(0)
        if tok in ("{{", "}}"):
            out.append(escape(tok[0]))
        else:
            plus, name = m.groups()
            if name in combo_text:
                text = combo_text[name]
                out.append(escape(text))
            else:
                if plus:
                    plus_names.add(name)
                out.append("${" + name + "}")
        pos = m.end()
    out.append(escape(syntax[pos:]))
    return "".join(out)


def escape(text):
    out = []
    for c in text:
        if c == "$":
            out.append("$$")
        elif c in "{}|\\":
            out.append("\\\\" + c)
        elif c == '"':
            out.append('\\"')
        else:
            out.append(c)
    return "".join(out)


def destination(syntax):
    """(field, tied) for a form that writes the field its syntax starts with, else (None, False)."""
    m = re.match(r"^\{(\w)\}(?:\{\w\})?\s*(\S+)\s", syntax)
    if not m:
        return None, False
    if m.group(2) == "=":
        partial = re.match(r"^\{\w\}\{\w\}", syntax) is not None      # {r}{n} = : a half of r
        return m.group(1), partial
    if m.group(2) in COMPOUND:
        return m.group(1), True
    return None, False


BRANCH_RELOC = {(2, 16): 1, (2, 22): 2, (3, 16): 3, (3, 31): 4}     # docs/ELF.md section 5


def abs32_field(insn):
    """The field of a 32-bit constant load, which can carry a relocation, or None."""
    for name, f in insn.fields.items():
        if f.kind == "uimm" and len(insn.field_bits(name)) == 32:
            return name
    return None


class Fixups:
    """One fixup kind per place an expression can go: instruction size, field bits, how a value becomes the
    field (raw = (value - add) / scale), pc-relative or not, and the ELF relocation (0: resolved here)."""

    def __init__(self):
        self.kinds = {}          # (nbits, positions, pcrel, scale, add, signed, reloc) -> index
        self.operand = {}        # (record name, MCInst operand index) -> kind index

    def add(self, insn, name, record, opno):
        pcrel = branch_field(insn) == name
        nbits = insn.nbits
        f = insn.fields[name]
        positions = tuple(nbits - 1 - pos for pos in insn.field_bits(name))
        if pcrel:                # (target - end of instruction) / 2
            scale, add, signed = 2, nbits // 8, True
            reloc = BRANCH_RELOC.get((len(insn.words), len(positions)), 0)
        elif name == abs32_field(insn):
            scale, add, signed, reloc = 1, 0, False, 5
        else:                    # a block's length or shape: resolved by the assembler
            scale, add, signed, reloc = f.scale, f.add, f.kind == "simm", 0
        key = (nbits, positions, pcrel, scale, add, signed, reloc)
        if key not in self.kinds:
            self.kinds[key] = len(self.kinds)
        self.operand[(record, opno)] = self.kinds[key]

    def cxx(self):
        out = [f"// {HEADER}", "#ifdef PI32V2_GEN_FIXUP_ENUM", "#undef PI32V2_GEN_FIXUP_ENUM"]
        keys = sorted(self.kinds, key=self.kinds.get)
        for k in keys:
            out.append(f"  fixup_pi32v2_{self.kinds[k]},")
        out += ["#endif", "#ifdef PI32V2_GEN_FIXUP_TABLE", "#undef PI32V2_GEN_FIXUP_TABLE",
                "// name, instruction bytes, pc-relative, ELF relocation (0: resolved by the assembler), scale,",
                "// add, signed, field width, the Inst bits of the field (most significant first)",
                "static const PI32V2FixupLayout FixupLayouts[] = {"]
        for k in keys:
            nbits, positions, pcrel, scale, add, signed, reloc = k
            out.append(f"    {{\"fixup_pi32v2_{self.kinds[k]}\", {nbits // 8}, {int(pcrel)}, {reloc}, {scale}, "
                       f"{add}, {int(signed)}, {len(positions)}, {{{', '.join(map(str, positions))}}}}},")
        out += ["};", "#endif", "#ifdef PI32V2_GEN_FIXUP_FOR_OPERAND", "#undef PI32V2_GEN_FIXUP_FOR_OPERAND",
                "static int fixupForOperand(unsigned Opcode, unsigned OpNo) {", "  switch (Opcode) {"]
        by_rec = {}
        for (rec, opno), k in self.operand.items():
            by_rec.setdefault(rec, []).append((opno, k))
        for rec, ops in by_rec.items():
            out.append(f"  case PI32V2::{rec}:")
            for opno, k in ops:
                out.append(f"    if (OpNo == {opno})\n      return {k};")
            out.append("    return -1;")
        out += ["  default:", "    return -1;", "  }", "}", "#endif"]
        return "\n".join(out) + "\n"


def generate(tab):
    import codegen_flags
    cg_flags = codegen_flags.flags()
    unknown = set(cg_flags) - {i.id for i in tab.insns}
    if unknown:
        raise SystemExit(f"codegen_flags.py names no table form: {sorted(unknown)}")
    ops = Operands()
    fixups = Fixups()
    records = {}         # record name -> (insn, {enum field: value}, [field per MCInst operand])
    td = [f"// {HEADER}\n"]
    ids = []
    count = 0
    for insn in tab.insns:
        enums = [n for n, f in insn.fields.items() if f.kind == "enum"]
        combos = list(product(*[range(len(insn.fields[n].values)) for n in enums]))
        dest, tied = destination(insn.syntax)
        for ci, combo in enumerate(combos):
            fixed = dict(zip(enums, combo))
            combo_text = {n: insn.fields[n].values[v] for n, v in fixed.items()}
            plus_names = set()
            asm = asm_string(insn.syntax, combo_text, plus_names)
            name = record_name(insn.id, ci, len(combos))
            nbits = insn.nbits
            outs, ins, body = [], [], []
            names = list(dict.fromkeys(n for n in table.placeholders(insn.syntax) if n not in fixed))
            names += [n for n in insn.fields if n not in fixed and n not in names]     # block-implied fields
            mc_order = []
            for n in names:
                if n == dest:
                    mc_order.insert(len([x for x in mc_order if x[1] == "out"]), (n, "out"))
                    if tied:
                        mc_order.append((n, "tied"))
                else:
                    mc_order.append((n, "in"))
            # MCInst order: outs, then ins (a tied input first among them)
            outs_f = [n for n, w in mc_order if w == "out"]
            ins_f = [n for n, w in mc_order if w == "tied"] + [n for n, w in mc_order if w == "in"]
            records[name] = (insn, fixed, outs_f + ins_f)
            for opno, n in enumerate(outs_f + ins_f):
                if n in (branch_field(insn), abs32_field(insn), insn.body, *insn.block.values()):
                    fixups.add(insn, n, name, opno)
            for n in names:
                op = ops.get(insn, n, n in plus_names)
                width = len(insn.field_bits(n))
                body.append(f"  bits<{width}> {n};")
                if n == dest:
                    outs.append(f"{op.td_name}:${n}")
                    if tied:
                        ins.insert(0, f"{op.td_name}:${n}_in")
                else:
                    ins.append(f"{op.td_name}:${n}")
            bits = ["?"] * nbits
            enc = "".join(insn.words)
            for pos, c in enumerate(enc):
                if c in "01":
                    bits[nbits - 1 - pos] = c
            for n in insn.fields:
                fb = insn.field_bits(n)
                w = len(fb)
                for k, pos in enumerate(fb):
                    if n in fixed:
                        bits[nbits - 1 - pos] = str((fixed[n] >> (w - 1 - k)) & 1)
                    else:
                        bits[nbits - 1 - pos] = f"{n}{{{w - 1 - k}}}"
            lets = []
            for b in range(nbits - 1, -1, -1):
                v = bits[b]
                if v == "?":
                    continue
                lets.append(f"  let Inst{{{b}}} = {v if v in '01' else v};")
            rec = [f"def {name} : PI32V2Inst{nbits}<(outs {', '.join(outs)}), (ins {', '.join(ins)}),"
                   f" \"{asm}\"> {{"]
            rec += body + lets
            if tied:
                rec.append(f"  let Constraints = \"${dest} = ${dest}_in\";")
            preds = [FEATURES[f] for f in insn.requires]
            if preds:
                rec.append(f"  let Predicates = [{', '.join(preds)}];")
            if insn.asm_no_syntax:
                rec.append("  let AsmVariantName = \"disasm\";")
            if insn.id in cg_flags:
                rec += [f"  {x}" for x in cg_flags[insn.id]]
            elif branch_field(insn):
                rec.append("  let isBranch = 1;" if "goto" in insn.syntax else "  let isCall = 1;")
            rec.append("}")
            td.append("\n".join(rec) + "\n")
            ids.append(f"{name} {insn.id} " + " ".join(f"{n}={v}" for n, v in fixed.items()))
            count += 1
    head = [f"// {HEADER}\n"] + [op.td for op in ops.by_key.values() if op.td]
    td_text = "".join(head) + "\n" + "".join(td[1:])
    inc = [f"// {HEADER}\n"]
    for section, macro in (("decoders", "PI32V2_GEN_DECODERS"), ("encoder_decls", "PI32V2_GEN_ENCODER_DECLS"),
                           ("encoders", "PI32V2_GEN_ENCODERS"), ("printer_decls", "PI32V2_GEN_PRINTER_DECLS"),
                           ("printers", "PI32V2_GEN_PRINTERS")):
        inc.append(f"#ifdef {macro}\n#undef {macro}\n{ops.cxx(section)}\n#endif // {macro}\n")
    return td_text, "\n".join(inc), "\n".join(ids) + "\n", count, fixups.cxx(), records, ops


def disasm_test(tab):
    lines = ["# " + HEADER, "# Every example of the table: llvm-mc prints the table's text.",
             "# RUN: llvm-mc --disassemble -triple=pi32v2 -mattr=+instrev3,+fprev1 %s | FileCheck %s", ""]
    for insn in tab.insns:
        for x in insn.examples:
            lines.append(f"# {insn.id}")
            check = "CHECK-NEXT" if any("CHECK" in ln and not ln.startswith("# RUN") for ln in lines[-3:]) else "CHECK"
            lines.append(f"# {check}: {{{{^ *}}}}{x.text.strip()}{{{{ *$}}}}")
            lines.append(" ".join(f"0x{b:02x}" for b in x.bytes))
    return "\n".join(lines) + "\n"


def asm_test(tab):
    """Every example's text (not the parallel halves, blocks or texts JieLi's assembler refuses) and the
    encoding this repo's assembler gives it."""
    from pi32v2isa import asm, elf
    lines = ["; " + HEADER, "; Every example of the table, in its assembler form: the encoding of pi32v2isa.asm.",
             "; RUN: llvm-mc -triple=pi32v2 -mattr=+instrev3,+fprev1 --show-encoding %s | FileCheck %s", ""]
    for insn in tab.insns:
        if insn.asm_no_syntax or insn.body or insn.block:
            continue
        for x in insn.examples:
            text = x.text.strip()
            if text in insn.asm_rejects or text in insn.asm_wrong or text.endswith("#"):
                continue
            try:
                obj = elf.read(asm.assemble_source(f"\t{text}\n", "x.s"))
            except Exception:
                continue
            data = next(bytes(sec.data) for sec in obj.sections if sec.name == ".text")
            lines.append(f"\t{text}")
            lines.append(f"; CHECK: encoding: [{','.join(f'0x{b:02x}' for b in data)}]")
    return "\n".join(lines) + "\n"


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("target_dir", type=Path)
    p.add_argument("--table", type=Path, default=table.TABLE)
    p.add_argument("--tests", type=Path, help="llvm/test/MC of the LLVM tree")
    a = p.parse_args()
    tab = table.load(a.table)
    td_text, inc, ids, count, fix, records, ops = generate(tab)
    import gen_parser
    parser_inc, relax_inc = gen_parser.generate(tab, records, HEADER)
    (a.target_dir / "AsmParser" / "PI32V2ParserGen.inc").write_text(parser_inc)
    (a.target_dir / "MCTargetDesc" / "PI32V2RelaxGen.inc").write_text(relax_inc)
    import gen_compress
    (a.target_dir / "MCTargetDesc" / "PI32V2CompressGen.inc").write_text(
        gen_compress.generate(tab, records, ops, HEADER))
    (a.target_dir / "MCTargetDesc" / "PI32V2FixupsGen.inc").write_text(fix)
    (a.target_dir / "PI32V2InstrGen.td").write_text(td_text)
    (a.target_dir / "PI32V2OperandsGen.inc").write_text(inc)
    (a.target_dir / "PI32V2InstrIds.txt").write_text(ids)
    if a.tests:
        d = a.tests / "Disassembler" / "PI32V2"
        d.mkdir(parents=True, exist_ok=True)
        (d / "examples.txt").write_text(disasm_test(tab))
        d = a.tests / "PI32V2"
        d.mkdir(parents=True, exist_ok=True)
        (d / "examples.s").write_text(asm_test(tab))
    print(f"{count} instructions from {len(tab.insns)} table forms -> {a.target_dir}")


if __name__ == "__main__":
    main()
